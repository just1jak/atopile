// Synthetic test fixture. No scanner, radio, or vehicle is used.
#include "chrysler/protocol.hpp"
#include "capture_format.hpp"
#include <fstream>
#include <iomanip>
#include <stdexcept>
#include <string>

int main() {
    std::ofstream raw("raw_0001.bin", std::ios::binary);
    std::ofstream csv("selected_0001.csv");
    if (!raw || !csv) throw std::runtime_error("cannot create synthetic output files");
    raw.write(capture::file_magic, 8);
    csv << "host_us,utc_us,scanner_ms,bus,profile,metric,value,unit\n";
    csv << std::fixed << std::setprecision(6);
    std::uint32_t sequence = 0;
    std::uint64_t host_us = 0;
    unsigned frames = 0, rows = 0;
    auto append = [&](capture::Type type, const std::uint8_t* bytes, std::size_t size) {
        const auto record = capture::record(type, sequence++, host_us, 0, 0, bytes, size);
        raw.write(reinterpret_cast<const char*>(record.data()), record.size());
        if (!raw) throw std::runtime_error("synthetic raw write failed");
    };
    auto note = [&](const std::string& text) {
        append(capture::Type::Event, reinterpret_cast<const std::uint8_t*>(text.data()), text.size());
    };
    chrysler::StreamParser parser([&](const chrysler::ParseEvent& event) {
        if (event.kind != chrysler::ParseEventKind::Packet)
            throw std::runtime_error("unexpected synthetic parser error");
        ++frames;
        append(capture::Type::ScannerFrame, event.frame.raw.data(), event.frame.raw.size());
        const auto message = chrysler::decode_receive(event.frame);
        if (!message) throw std::runtime_error("synthetic RX frame rejected");
        const auto decoded = chrysler::decode_metrics(*message, chrysler::DecoderProfile::UpstreamBroadcast2023);
        if (decoded.disposition != chrysler::DecodeDisposition::Decoded)
            throw std::runtime_error("synthetic bus checksum/profile rejected");
        for (const auto& metric : decoded.metrics) {
            csv << host_us << ",0," << message->scanner_ms
                << ",PCI,upstream_broadcast_2023,\"" << metric.id << "\","
                << metric.value << ",\"" << metric.unit << "\"\n";
            ++rows;
        }
    });
    auto chunk = [&](const chrysler::Bytes& bytes, std::uint64_t time) {
        host_us = time;
        append(capture::Type::BleChunk, bytes.data(), bytes.size());
        parser.feed(bytes);
    };
    note("SYNTHETIC TEST FIXTURE: generated bytes; no scanner, radio, vehicle, UTC clock, or physical capture.");
    // Official protocol shape and upstream formulas, with independently specified
    // PCI CRC bytes 17/DF and outer frame checksums 1F/B6. Values are invented.
    const chrysler::Bytes rpm{0x3d,0,0x0d,0xc7,1,0,0,3,0xe8,0x10,0x1f,0x40,0x27,0x10,0x65,0x17,0x1f};
    const chrysler::Bytes engine{0x3d,0,0x0c,0xc7,1,0,0,3,0xf2,0xc0,0xe0,0x64,0x7d,0x50,0xdf,0xb6};
    chunk(chrysler::Bytes(rpm.begin(), rpm.begin() + 8), 1000000);
    chunk(chrysler::Bytes(rpm.begin() + 8, rpm.end()), 1000100);
    chunk(engine, 1010000);
    parser.finish();
    note("SYNTHETIC TEST COMPLETE: two validated PCI frames, seven decoded rows; not hardware validation.");
    if (frames != 2 || rows != 7 || parser.pending_bytes())
        throw std::runtime_error("unexpected synthetic fixture result");
    raw.close(); csv.close();
    if (!raw || !csv) throw std::runtime_error("synthetic close failed");
}
