def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def stock(footprint,directory,basename=None,notes='',rotation=None):
    basename=basename or footprint
    rel=directory+'.3dshapes/'+basename+'.step'
    src=args.kicad_models_root/rel;assert src.is_file(),src
    dst=DEST/src.name;shutil.copyfile(src,dst)
    models.setdefault(dst.name,{'kind':'KiCad standard package','source':'https://gitlab.com/kicad/libraries/kicad-packages3D/-/blob/master/'+rel,
        'license':'CC-BY-SA-4.0 with KiCad library exception','sha256':sha(dst),'notes':notes or 'Generic package; does not establish an orderable manufacturer part.'})
    spec={'model':dst.name}
    if notes:spec['assignment_notes']=notes
    if rotation:spec['rotation_deg']=rotation
    if footprint:footprints[footprint]=spec
    return spec

