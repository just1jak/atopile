def box(cx,cy,z,w,d,h):
    """Position by footprint-local XY, with Y inverted for 3D coordinates."""
    return Part.makeBox(w,d,h,App.Vector(cx-w/2,-cy-d/2,z))

def cylinder(cx,cy,z,r,h):
    return Part.makeCylinder(r,h,App.Vector(cx,-cy,z))

def profile_x(points,x,length):
    # points are (footprint y, z) pairs.
    vertices=[App.Vector(x,-y,z) for y,z in points]
    wire=Part.makePolygon(vertices+[vertices[0]])
    return Part.Face(wire).extrude(App.Vector(length,0,0))

def export_model(basename,items,notes,documents,kind='Dimension-based representative'):
    # Parts are kept separate for readable CAD solids and colored VRML rendering.
    doc=App.newDocument(basename);objects=[]
    for i,(label,shape,color) in enumerate(items):
        assert shape.isValid() and shape.Volume>0,(basename,label)
        obj=doc.addObject('PartDesign::Feature','Solid'+str(i));obj.Label=label;obj.Shape=shape;objects.append(obj)
    doc.recompute()
    step=DEST/(basename+'.step');Part.export(objects,str(step))
    wrl=DEST/(basename+'.wrl')
    lines=['#VRML V2.0 utf8','# GPL-3.0-or-later. Representative geometry generated by scripts/generate_3d_models.py.',
        '# Dimensions: KiCad legacy VRML units (1 unit = 2.54 mm).']
    for label,shape,color in items:
        verts,faces=shape.tessellate(.05)
        pts=',\n'.join(' '.join(f'{v:.7f}' for v in (p.x/2.54,p.y/2.54,p.z/2.54)) for p in verts)
        inds=',\n'.join(' '.join(map(str,(*f,-1))) for f in faces)
        lines.append('# '+label+'\nShape { appearance Appearance { material Material { diffuseColor '+
            ' '.join(map(str,color))+' specularColor 0.25 0.25 0.25 shininess 0.4 } } '+
            'geometry IndexedFaceSet { coord Coordinate { point [\n'+pts+'\n] } coordIndex [\n'+inds+'\n] solid TRUE creaseAngle 0.5 } }')
    wrl.write_text('\n'.join(lines)+'\n')
    bound=Part.makeCompound([q[1] for q in items]).BoundBox
    metadata={'kind':kind,'license':'GPL-3.0-or-later','generator':'scripts/generate_3d_models.py','notes':notes,
        'dimension_sources':documents,'bounds_3d_mm':[bound.XMin,bound.YMin,bound.ZMin,bound.XMax,bound.YMax,bound.ZMax]}
    models[wrl.name]={**metadata,'sha256':sha(wrl),'step_companion':step.name}
    models[step.name]={**metadata,'sha256':sha(step)}
    App.closeDocument(doc.Name)
    return {'model':wrl.name}

